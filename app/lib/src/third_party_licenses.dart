/// Adds the entries to Flutter's licence registry (shown by showLicensePage).
void registerThirdPartyLicenses() {
  // SDL3 is only in the desktop host library (desktop-shell.md).
  if (shellProfile == ShellProfile.desktop) {
    LicenseRegistry.addLicense(
      () => Stream.value(
        const LicenseEntryWithLineBreaks(['SDL3 (desktop)'], _sdl3),
      ),
    );
  }
  LicenseRegistry.addLicense(
    () => Stream.fromIterable(const [
      LicenseEntryWithLineBreaks([
        'Box-art index (libretro-database)',
      ], _boxArt),
      LicenseEntryWithLineBreaks([
        'Cheat database (libretro-database)',
      ], _cheats),
      LicenseEntryWithLineBreaks(['melonDS FreeBIOS (DS)'], _freeBios),
      LicenseEntryWithLineBreaks(['libchdr (PlayStation)'], _libchdr),
      LicenseEntryWithLineBreaks(['Bundled shaders'], _shaders),
      LicenseEntryWithLineBreaks(['Roboto (font)'], _roboto),
      LicenseEntryWithLineBreaks(['IBM Plex Mono (font)'], _plexMono),
      LicenseEntryWithLineBreaks(['Archivo Black (font)'], _archivoBlack),
      LicenseEntryWithLineBreaks(['rcheevos (RetroAchievements)'], _rcheevos),
    ]),
  );
}
