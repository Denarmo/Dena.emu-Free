#!/usr/bin/env python3
"""Regenerate every app icon from docs/branding/logo.svg.

Writes the Android adaptive icon (vector foreground, monochrome layer and
background colour), the legacy Android mipmaps, the iOS AppIcon set and the
512px store/README icon. Needs `pip install cairosvg pillow`.

Run from anywhere: python3 tools/branding/gen_icons.py
"""
import io
import json
import re
from pathlib import Path

import cairosvg
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[2]
SVG = ROOT / "docs" / "branding" / "logo.svg"
RES = ROOT / "app" / "android" / "app" / "src" / "main" / "res"
IOS = ROOT / "app" / "ios" / "Runner" / "Assets.xcassets" / "AppIcon.appiconset"

BACKGROUND = "#16181D"
LETTER = "#F5F6F7"
ACCENT = "#F1C40F"

# Shapes shared by the SVG and the Android vector drawables (108-unit canvas).
D_PATH = "M33.5,39.5 H46.5 A14.5,14.5 0 0 1 46.5,68.5 H33.5 Z"
DOT_PATH = "M67.5,67.5 a4.5,4.5 0 1 0 9,0 a4.5,4.5 0 1 0 -9,0 Z"
SHIFT_X = 0.75
SCALE = 0.86  # breathing room inside circular launcher masks


def render(size, crop=108.0, mask_radius=None):
    """Render the logo cropped to the centred `crop` units, at size x size."""
    svg = SVG.read_text()
    off = (108.0 - crop) / 2
    svg = re.sub(r'viewBox="[^"]*"', f'viewBox="{off} {off} {crop} {crop}"', svg, count=1)
    png = cairosvg.svg2png(bytestring=svg.encode(), output_width=size, output_height=size)
    img = Image.open(io.BytesIO(png)).convert("RGBA")
    if mask_radius is not None:
        mask = Image.new("L", (size * 4, size * 4), 0)
        ImageDraw.Draw(mask).rounded_rectangle(
            (0, 0, size * 4 - 1, size * 4 - 1), radius=int(size * 4 * mask_radius), fill=255)
        img.putalpha(mask.resize((size, size), Image.LANCZOS))
    return img


def vector(paths):
    body = "\n".join(paths)
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/branding/gen_icons.py from docs/branding/logo.svg. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <group
        android:pivotX="54"
        android:pivotY="54"
        android:scaleX="{SCALE}"
        android:scaleY="{SCALE}"
        android:translateX="{SHIFT_X}">
{body}
    </group>
</vector>
"""


def letter(color):
    return f"""        <path
            android:pathData="{D_PATH}"
            android:strokeColor="{color}"
            android:strokeWidth="7"
            android:strokeLineJoin="round" />"""


def dot(color):
    return f"""        <path
            android:pathData="{DOT_PATH}"
            android:fillColor="{color}" />"""


def android():
    (RES / "drawable" / "ic_launcher_foreground.xml").write_text(
        vector([letter(LETTER), dot(ACCENT)]))
    (RES / "drawable" / "ic_launcher_monochrome.xml").write_text(
        vector([letter("#FFFFFFFF"), dot("#FFFFFFFF")]))
    (RES / "values" / "ic_launcher_background.xml").write_text(
        f"""<?xml version="1.0" encoding="utf-8"?>
<resources>
    <color name="ic_launcher_background">{BACKGROUND}</color>
</resources>
""")
    anydpi = RES / "mipmap-anydpi-v26"
    anydpi.mkdir(exist_ok=True)
    (anydpi / "ic_launcher.xml").write_text(
        """<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
""")
    # Legacy bitmaps: the 72-unit visible area, rounded like a squircle.
    for density, px in {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}.items():
        render(px, crop=72, mask_radius=0.22).save(RES / f"mipmap-{density}" / "ic_launcher.png")


def ios():
    contents = json.loads((IOS / "Contents.json").read_text())
    for image in contents["images"]:
        points = float(image["size"].split("x")[0])
        scale = int(image["scale"].rstrip("x"))
        # iOS masks the corners itself and rejects alpha, so stay opaque.
        render(round(points * scale), crop=76).convert("RGB").save(IOS / image["filename"])


def store():
    render(512, crop=76).convert("RGB").save(ROOT / "docs" / "branding" / "icon-512.png")


if __name__ == "__main__":
    android()
    ios()
    store()
